const MOSCOW_AREA = new Set(["Москва", "Балашиха", "Подольск", "Химки", "Мытищи", "Королёв", "Люберцы",
  "Красногорск", "Одинцово", "Домодедово", "Электросталь", "Серпухов", "Коломна", "Пушкино", "Щёлково"]);

export const normalize = (s: string) => s.toLowerCase().replace(/ё/g, "е").trim();

/** Сначала города, начинающиеся с введённого, потом те, где совпадение в середине слова */
export function searchCities(query: string, limit = 8) {
  const q = normalize(query);
  if (!q) return [];
  const starts: string[] = [];
  const inside: string[] = [];
  for (const city of CITIES) {
    const n = normalize(city);
    if (n.startsWith(q)) starts.push(city);
    else if (n.split(/[\s-]/).some((part) => part.startsWith(q))) inside.push(city);
  }
  return [...starts, ...inside].slice(0, limit);
}

export function isKnownCity(name: string) {
  return (CITIES as readonly string[]).includes(name);
}

export function deliveryInfo(city: string) {
  if (MOSCOW_AREA.has(city)) return { courier: "завтра", pickup: "сегодня", courierPrice: 0 };
  if (city === "Санкт-Петербург") return { courier: "через 1–2 дня", pickup: "завтра", courierPrice: 0 };
  return { courier: "через 2–5 дней", pickup: "через 2–4 дня", courierPrice: 49000 };
}
